# ============================================================
#                 EXPONENT / POWER IN PYTHON
# ============================================================


# ============================================================
# 1. ** Operator
# ============================================================

print(2 ** 3)       # 8
print(5 ** 2)       # 25

# 2 ** 3 means:
# 2 × 2 × 2 = 8


# ============================================================
# 2. pow() function
# ============================================================

print(pow(2, 3))    # 8

# pow(base, exponent)

print(pow(5, 2))    # 25


# ============================================================
# 3. pow() with modulo
# ============================================================

# pow(base, exponent, modulo)
#
# Calculates:
# (base ** exponent) % modulo

print(pow(2, 10, 1000))

# Same as:
# (2 ** 10) % 1000


# ============================================================
# 4. Taking input
# ============================================================

base = int(input("Enter base: "))
exponent = int(input("Enter exponent: "))

result = base ** exponent

print("Result:", result)


# ============================================================
# 5. Negative and fractional exponents
# ============================================================

print(2 ** -2)       # 0.25
print(16 ** 0.5)     # 4.0

# x ** 0.5 is the square root of x