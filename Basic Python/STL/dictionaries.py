# ============================================================
#                    PYTHON DICTIONARY
# ============================================================

# A dictionary stores data as KEY : VALUE pairs.

student = {
    "name": "Harsh",
    "age": 22,
    "marks": 90
}

print(student)


# ============================================================
# 1. Accessing values
# ============================================================

print(student["name"])
print(student["age"])


# ============================================================
# 2. get() - Safely access a value
# ============================================================

print(student.get("marks"))

# If key doesn't exist, get() returns None
# instead of giving an error.

print(student.get("city"))


# ============================================================
# 3. Adding a new key-value pair
# ============================================================

student["city"] = "Lucknow"

print(student)


# ============================================================
# 4. Updating a value
# ============================================================

student["marks"] = 95

print(student)


# ============================================================
# 5. pop() - Remove a key-value pair
# ============================================================

student.pop("age")

print(student)


# ============================================================
# 6. keys() - Get all keys
# ============================================================

print(student.keys())


# ============================================================
# 7. values() - Get all values
# ============================================================

print(student.values())


# ============================================================
# 8. items() - Get key and value together
# ============================================================

print(student.items())


# ============================================================
# 9. Checking if a key exists
# ============================================================

print("name" in student)
print("age" not in student)


# ============================================================
# 10. Loop through dictionary
# ============================================================

for key, value in student.items():
    print(key, ":", value)


# ============================================================
# 11. len() - Number of key-value pairs
# ============================================================

print("Size:", len(student))


# ============================================================
# 12. clear() - Remove everything
# ============================================================

student.clear()

print(student)           # {}