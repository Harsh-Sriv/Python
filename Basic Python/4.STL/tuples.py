# ============================================================
#                       PYTHON TUPLE
# ============================================================

# A tuple is like a list, but it CANNOT be changed after creation.
# Tuples are ordered and allow duplicate values.

numbers = (10, 20, 30, 20, 40)

print("Tuple:", numbers)


# ============================================================
# 1. Accessing elements
# ============================================================

print(numbers[0])       # First element
print(numbers[-1])      # Last element


# ============================================================
# 2. Slicing
# ============================================================

print(numbers[1:4])


# ============================================================
# 3. count() - Count occurrences
# ============================================================

print(numbers.count(20))


# ============================================================
# 4. index() - Find position
# ============================================================

print(numbers.index(30))


# ============================================================
# 5. len() - Find size
# ============================================================

print(len(numbers))


# ============================================================
# 6. Membership
# ============================================================

print(30 in numbers)
print(100 not in numbers)


# ============================================================
# 7. Tuple unpacking
# ============================================================

person = ("Harsh", 22, "India")

name, age, country = person

print(name)
print(age)
print(country)


# ============================================================
# IMPORTANT
# ============================================================

# Tuples are immutable.
# The following will give an error:
#
# numbers[0] = 100
#
# Use a list if you need to modify the elements.